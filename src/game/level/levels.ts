/**
 * Level map definitions for all 9 sandwich-ingredient levels.
 *
 * Tile legend:
 *   #  solid ground
 *   .  air
 *   P  spawn point
 *   G  goal (exit)
 *   S  spikes (kills on contact)
 *   C  collectible ingredient
 *   M  mushroom enemy spawn
 *   L  land mine
 *
 * Rows are automatically padded to the widest row, so trailing dots can
 * be omitted while editing.
 */

/** A floating island that slides back and forth along a fixed path. */
export interface MovingPlatformSpec {
  /** Top-left tile of the platform at phase 0. */
  x: number;
  y: number;
  /** Platform width in tiles. */
  width: number;
  /** Travel distance in tiles from the starting point. */
  dx: number;
  dy: number;
  /** Time for one complete there-and-back cycle, in ms. */
  periodMs: number;
  /** 0..1 offset into the cycle, so platforms can start out of sync. */
  phase?: number;
}

/** A buzzsaw that sweeps along a straight track. */
export interface SawSpec {
  /** Tile at the centre of the track at phase 0. */
  x: number;
  y: number;
  dx: number;
  dy: number;
  periodMs: number;
  radius?: number;
  phase?: number;
}

/** A cannon emplacement that fires straight-line projectiles. */
export interface CannonSpec {
  /** Tile the cannon is mounted on. */
  x: number;
  y: number;
  /** Fixed firing direction; omit to aim at the player while charging. */
  dir?: { x: number; y: number };
  intervalMs: number;
  /** Projectile speed in px/s. */
  speed: number;
  /** Telegraph time before firing, in ms. */
  chargeMs?: number;
  /** Delay before the first shot, in ms. */
  delayMs?: number;
}

export interface LevelInfo {
  id: number;
  name: string;
  section: string;
  ingredient: string;
  map: readonly string[];
  platforms?: MovingPlatformSpec[];
  saws?: SawSpec[];
  cannons?: CannonSpec[];
}

